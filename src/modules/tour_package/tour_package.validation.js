const Joi = require('joi');

exports.create = Joi.object({
  provider_name: Joi.string().max(200).optional().default('Vendor'),
  title: Joi.string().min(1).max(200).required(),
  description: Joi.string().max(5000).allow('', null).optional(),
  price: Joi.number().min(0).optional().default(0),
  price_range: Joi.string().allow('', null).optional(),
  duration: Joi.string().max(50).allow('', null).optional(),
  category: Joi.string().optional().default('UMRAH'),
  contact_whatsapp: Joi.string().max(20).allow('', null).optional(),
  whatsapp_phone: Joi.string().max(20).allow('', null).optional(),
  slots: Joi.number().optional().default(10),
  website: Joi.string().max(200).allow('', null).optional(),
  image_url: Joi.string().allow('', null).optional(),
  imageUrl: Joi.string().allow('', null).optional(),
  logo_url: Joi.string().allow('', null).optional(),
  about: Joi.string().max(2000).allow('', null).optional(),
  total_slots: Joi.number().integer().min(0).optional().default(10),
  booked_slots: Joi.number().integer().min(0).optional().default(0),
  start_date: Joi.date().iso().allow(null).optional(),
  end_date: Joi.date().iso().allow(null).optional(),
}).unknown(true);

exports.update = Joi.object({
  provider_name: Joi.string().max(200),
  title: Joi.string().min(1).max(200),
  description: Joi.string().max(5000).allow('', null),
  price: Joi.number().min(0),
  price_range: Joi.string().allow('', null),
  duration: Joi.string().max(50).allow('', null),
  category: Joi.string(),
  contact_whatsapp: Joi.string().max(20).allow('', null),
  whatsapp_phone: Joi.string().max(20).allow('', null),
  website: Joi.string().max(200).allow('', null),
  image_url: Joi.string().allow('', null),
  imageUrl: Joi.string().allow('', null),
  logo_url: Joi.string().allow('', null),
  about: Joi.string().max(2000).allow('', null),
  total_slots: Joi.number().integer().min(0),
  booked_slots: Joi.number().integer().min(0),
  start_date: Joi.date().iso().allow(null),
  end_date: Joi.date().iso().allow(null),
  is_active: Joi.number().valid(0, 1),
}).unknown(true);
